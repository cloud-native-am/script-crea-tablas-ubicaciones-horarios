TRUNCATE TABLE LOG_UBICACION_VEHICULO;
TRUNCATE TABLE LOG_HORARIO_VEHICULO;


-- TABLA LOG DE UBICACIONES DESDE TOPIC UBICACIONES_VEHICULOS
CREATE TABLE LOG_UBICACION_VEHICULO (
    ID                  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PATENTE             VARCHAR2(10)    NOT NULL,
    LATITUD             NUMBER(18, 15)   NOT NULL,
    LONGITUD            NUMBER(18, 15)   NOT NULL,
    FECHA_ACTUALIZACION TIMESTAMP       NOT NULL
);


-- TABLA LOG DE HORARIOS DESDE TOPIC HORARIOS
CREATE TABLE LOG_HORARIO_VEHICULO (
    ID                           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PATENTE                      VARCHAR2(10)   NOT NULL,
    LATITUD                      NUMBER(18, 15)  NOT NULL,
    LONGITUD                     NUMBER(18, 15) NOT NULL,
    HORA_ACTUALIZACION           TIMESTAMP      NOT NULL,
    HORA_ESTIMADA_PROXIMA_PARADA TIMESTAMP      NOT NULL,
    TURNO                        VARCHAR2(10)   NOT NULL,
    CIUDAD_ORIGEN                VARCHAR2(50)   NOT NULL,
    CIUDAD_DESTINO               VARCHAR2(50)   NOT NULL
);


COMMIT;


select * from LOG_UBICACION_VEHICULO ORDER BY FECHA_ACTUALIZACION ASC;

select * from LOG_HORARIO_VEHICULO ORDER BY HORA_ACTUALIZACION ASC;
